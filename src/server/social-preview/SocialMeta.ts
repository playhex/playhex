import type { TFunction } from 'i18next';
import { seo } from '../../shared/app/seo.js';

export const supportedSocialLocales = ['en', 'fr'] as const;

export type SocialLocale = typeof supportedSocialLocales[number];

export const isSupportedSocialLocale = (locale: unknown): locale is SocialLocale =>
    supportedSocialLocales.includes(locale as SocialLocale)
;

/**
 * og:locale values, see https://ogp.me/#optional
 */
export const ogLocales: { [locale in SocialLocale]: string } = {
    en: 'en_US',
    fr: 'fr_FR',
};

export type SocialImage = {
    url: string;
    width: number;
    height: number;
    alt: string;
};

export type JsonLd = { [key: string]: unknown };

/**
 * Meta tags rendered in page <head>, read by social networks crawlers and search engines.
 */
export type SocialMeta = {
    title: string;
    description: string;

    /**
     * Canonical absolute url of the page.
     */
    url: string;

    image: SocialImage;
    type: 'website' | 'article' | 'profile';
    locale: SocialLocale;
    noindex: boolean;
    jsonLd: JsonLd[];
};

/**
 * What meta builders need to build translated meta for a page.
 */
export type SocialMetaContext = {
    t: TFunction;
    locale: SocialLocale;

    /**
     * e.g "https://playhex.org", without trailing slash.
     */
    baseUrl: string;

    /**
     * Absolute url of current page.
     */
    url: string;
};

/**
 * e.g "https://playhex.org", without trailing slash.
 */
export const socialBaseUrl = (): string => (process.env.BASE_URL ?? '').replace(/\/+$/, '');

export const OG_IMAGE_WIDTH = 1200;
export const OG_IMAGE_HEIGHT = 630;

export const defaultSocialImage = (baseUrl: string): SocialImage => ({
    url: `${baseUrl}/images/social-preview.jpg`,
    width: OG_IMAGE_WIDTH,
    height: OG_IMAGE_HEIGHT,
    alt: seo.title,
});

/**
 * Image generated by ogImageRouter, with locale and version to refresh crawlers caches when content changes.
 */
export const ogImage = (context: SocialMetaContext, path: string, version: string, alt: string): SocialImage => {
    const params = new URLSearchParams({ lang: context.locale, v: version });

    return {
        url: `${context.baseUrl}/og/${path}.png?${params.toString()}`,
        width: OG_IMAGE_WIDTH,
        height: OG_IMAGE_HEIGHT,
        alt,
    };
};

export const websiteJsonLd = (baseUrl: string): JsonLd => ({
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    '@id': `${baseUrl}/#website`,
    name: seo.title,
    url: `${baseUrl}/`,
    publisher: {
        '@type': 'Organization',
        '@id': `${baseUrl}/#organization`,
        name: seo.title,
        url: `${baseUrl}/`,
        logo: `${baseUrl}/images/logo.png`,
        sameAs: [
            'https://github.com/playhex/playhex',
            'https://discord.gg/59SJ9KwvVq',
        ],
    },
});

export const createDefaultSocialMeta = (context: SocialMetaContext): SocialMeta => ({
    title: seo.title,
    description: context.t('social_preview.default_description'),
    url: context.url,
    image: defaultSocialImage(context.baseUrl),
    type: 'website',
    locale: context.locale,
    noindex: false,
    jsonLd: [websiteJsonLd(context.baseUrl)],
});

/**
 * Title shown in social previews, suffixed by site name.
 */
export const withSiteName = (title: string): string => `${title} - ${seo.title}`;
